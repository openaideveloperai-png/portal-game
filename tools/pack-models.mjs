// Pack the character models into one script (base64 glTF binaries on window.TARE_MODELS)
// for hosts that refuse to serve .glb files. The game uses it when the page loads it
// before the game script; otherwise it fetches the .glb files as usual.
// Usage: node tools/pack-models.mjs [modelsDir] [outFile]
import fs from 'node:fs';
import path from 'node:path';

const dir = process.argv[2] || 'dist/assets/models';
const out = process.argv[3] || path.join(dir, '..', 'models.js');
const files = fs.readdirSync(dir).filter(f => f.endsWith('.glb')).sort();
const entries = files.map(f => `${JSON.stringify(f.replace(/\.glb$/, ''))}: ${JSON.stringify(fs.readFileSync(path.join(dir, f)).toString('base64'))}`);
fs.writeFileSync(out, `// TARE character models (glTF binary, base64). Generated by tools/pack-models.mjs.\nwindow.TARE_MODELS = {\n${entries.join(',\n')}\n};\n`);
console.log(`packed ${files.length} models into ${out} (${(fs.statSync(out).size / 1048576).toFixed(1)} MB)`);
